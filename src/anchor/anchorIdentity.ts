import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { Project } from 'ts-morph';
import { canonicalPath } from '../verification/pathSafety.js';

export const anchorMarker = '// Generated by VibeDebt.';
export function validateAnchor(file: string, entry: string): void {
  const text = readFileSync(file, 'utf8');
  const project = new Project({ useInMemoryFileSystem: true });
  const source = project.createSourceFile('anchor.ts', text);
  const boundary = source.getImportDeclarations().find(i => i.getNamespaceImport()?.getText() === 'api');
  const path = boundary?.getModuleSpecifierValue();
  const expected = canonicalPath(entry);
  const declaration = `// VibeDebt anchor entry: ${JSON.stringify(expected)}`;
  if (!text.startsWith(anchorMarker) || !text.split(/\r?\n/).includes(declaration) || !path?.startsWith('.') ||
      canonicalPath(resolve(dirname(file), /\.tsx?$/.test(path) ? path : path + '.ts')) !== expected) {
    throw new Error('Anchor must be generated by VibeDebt for this target entry point');
  }
}
