import { relative, dirname, resolve } from 'node:path';
import { scenarios } from './scenarios.js';
import { canonicalPath } from '../verification/pathSafety.js';

export function synthesize(entry: string, output: string, expected?: Record<string, unknown>, capture?: string): string {
  let specifier = relative(dirname(resolve(output)), entry).replaceAll('\\', '/').replace(/\.ts$/, '');
  if (!specifier.startsWith('.')) specifier = './' + specifier;
  const header = `// Generated by VibeDebt. Public exports only; observed values are frozen before healing.
// VibeDebt anchor entry: ${JSON.stringify(canonicalPath(entry))}
import { beforeEach, afterEach, afterAll, it, expect, vi } from 'vitest';
import * as api from ${JSON.stringify(specifier)};
${capture ? "import { writeFileSync } from 'node:fs';\nconst observed: Record<string, unknown> = {};" : ''}
const item = (price: number, quantity = 1): api.CartItem => ({
  id: 'item', productId: 'product', sku: 'SKU', name: 'Anchor item', price, quantity, category: 'electronics',
});
const errorOf = (fn: () => unknown): string => { try { fn(); return 'NO_ERROR'; }
  catch (error) { return error instanceof Error ? error.message : String(error); } };
beforeEach(() => { vi.useFakeTimers(); vi.setSystemTime(new Date('2026-01-01T00:00:00.000Z')); api.resetMockDb(); });
afterEach(() => { api.restoreOriginalFetch(); vi.useRealTimers(); });
${capture ? `afterAll(() => writeFileSync(${JSON.stringify(capture)}, JSON.stringify(observed)));` : ''}
`;
  return header + scenarios().map(s => `
it(${JSON.stringify(s.name)}, async () => {
  const actual: unknown = JSON.parse(JSON.stringify({value: await (${s.expression})}));
  ${capture ? `observed[${JSON.stringify(s.name)}] = actual;` : `expect(actual).toEqual(${JSON.stringify(expected?.[s.name])});`}
});
`).join('');
}
